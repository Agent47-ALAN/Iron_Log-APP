import 'package:hive_flutter/hive_flutter.dart';
import '../models/exercise.dart';
import '../models/workout.dart';
import '../models/workout_set.dart';
import '../models/workout_exercise.dart';
import '../models/routine.dart';

class HiveService {
  static const String _workoutsBox = 'workouts';
  static const String _routinesBox = 'routines';
  static const String _exercisesBox = 'exercises';
  static const String _activeWorkoutBox = 'activeWorkout';

  // ─── Init ─────────────────────────────────────────────────
  static Future<void> init() async {
    await Hive.initFlutter();

    // Register adapters (generated by hive_generator)
    Hive.registerAdapter(ExerciseAdapter());
    Hive.registerAdapter(WorkoutSetAdapter());
    Hive.registerAdapter(WorkoutExerciseAdapter());
    Hive.registerAdapter(WorkoutAdapter());
    Hive.registerAdapter(RoutineExerciseAdapter());
    Hive.registerAdapter(RoutineAdapter());

    // Open boxes
    await Hive.openBox<Workout>(_workoutsBox);
    await Hive.openBox<Routine>(_routinesBox);
    await Hive.openBox<Exercise>(_exercisesBox);
    await Hive.openBox(_activeWorkoutBox); // dynamic box for active workout
  }

  // ─── Workout operations ───────────────────────────────────
  Box<Workout> get _workouts => Hive.box<Workout>(_workoutsBox);

  Future<void> saveWorkout(Workout workout) async {
    await _workouts.put(workout.id, workout);
  }

  Future<void> deleteWorkout(String id) async {
    await _workouts.delete(id);
  }

  List<Workout> getAllWorkouts() {
    final workouts = _workouts.values.toList();
    workouts.sort((a, b) => b.startTime.compareTo(a.startTime));
    return workouts;
  }

  Workout? getWorkout(String id) => _workouts.get(id);

  List<Workout> getCompletedWorkouts() {
    return getAllWorkouts().where((w) => w.isCompleted).toList();
  }

  List<Workout> getUnsyncedWorkouts() {
    return _workouts.values.where((w) => !w.isSynced).toList();
  }

  // ─── Active workout (in-progress session) ─────────────────
  Box get _activeBox => Hive.box(_activeWorkoutBox);

  Future<void> saveActiveWorkout(Map<String, dynamic> data) async {
    await _activeBox.put('current', data);
  }

  Map<String, dynamic>? getActiveWorkout() {
    final data = _activeBox.get('current');
    if (data == null) return null;
    return Map<String, dynamic>.from(data as Map);
  }

  Future<void> clearActiveWorkout() async {
    await _activeBox.delete('current');
  }

  // ─── Routine operations ───────────────────────────────────
  Box<Routine> get _routines => Hive.box<Routine>(_routinesBox);

  Future<void> saveRoutine(Routine routine) async {
    await _routines.put(routine.id, routine);
  }

  Future<void> deleteRoutine(String id) async {
    await _routines.delete(id);
  }

  List<Routine> getAllRoutines() {
    final routines = _routines.values.toList();
    routines.sort((a, b) => b.createdAt.compareTo(a.createdAt));
    return routines;
  }

  Routine? getRoutine(String id) => _routines.get(id);

  // ─── Exercise operations ──────────────────────────────────
  Box<Exercise> get _exercises => Hive.box<Exercise>(_exercisesBox);

  Future<void> saveExercise(Exercise exercise) async {
    await _exercises.put(exercise.id, exercise);
  }

  Future<void> saveAllExercises(List<Exercise> exercises) async {
    final map = {for (var e in exercises) e.id: e};
    await _exercises.putAll(map);
  }

  Future<void> deleteExercise(String id) async {
    await _exercises.delete(id);
  }

  List<Exercise> getAllExercises() {
    final exercises = _exercises.values.toList();
    exercises.sort((a, b) => a.name.compareTo(b.name));
    return exercises;
  }

  Exercise? getExercise(String id) => _exercises.get(id);

  List<Exercise> searchExercises(String query) {
    final q = query.toLowerCase();
    return getAllExercises()
        .where((e) =>
            e.name.toLowerCase().contains(q) ||
            e.muscleGroup.toLowerCase().contains(q))
        .toList();
  }

  List<Exercise> getExercisesByMuscleGroup(String group) {
    return getAllExercises()
        .where((e) => e.muscleGroup.toLowerCase() == group.toLowerCase())
        .toList();
  }

  bool get hasExercises => _exercises.isNotEmpty;

  // ─── Analytics helpers ────────────────────────────────────

  /// Volume per week for the last N weeks
  Map<DateTime, double> getWeeklyVolume({int weeks = 8}) {
    final now = DateTime.now();
    final result = <DateTime, double>{};

    for (int i = weeks - 1; i >= 0; i--) {
      final weekStart = now.subtract(Duration(days: now.weekday - 1 + (i * 7)));
      final weekKey = DateTime(weekStart.year, weekStart.month, weekStart.day);
      result[weekKey] = 0;
    }

    for (final workout in getCompletedWorkouts()) {
      final d = workout.startTime;
      final weekStart =
          d.subtract(Duration(days: d.weekday - 1));
      final weekKey =
          DateTime(weekStart.year, weekStart.month, weekStart.day);
      if (result.containsKey(weekKey)) {
        result[weekKey] = (result[weekKey] ?? 0) + workout.totalVolume;
      }
    }

    return result;
  }

  /// All-time personal records per exercise (best estimated 1RM)
  Map<String, double> getPersonalRecords() {
    final records = <String, double>{};

    for (final workout in getCompletedWorkouts()) {
      for (final ex in workout.exercises) {
        for (final set in ex.sets) {
          if (!set.isCompleted || set.isWarmup) continue;
          final oneRM = set.estimatedOneRepMax;
          if (oneRM == null) continue;
          final current = records[ex.exerciseId] ?? 0;
          if (oneRM > current) records[ex.exerciseId] = oneRM;
        }
      }
    }

    return records;
  }

  /// PR history for a specific exercise over time
  List<MapEntry<DateTime, double>> getExercisePRHistory(String exerciseId) {
    final history = <MapEntry<DateTime, double>>[];

    final workouts = getCompletedWorkouts()
      ..sort((a, b) => a.startTime.compareTo(b.startTime));

    double currentBest = 0;

    for (final workout in workouts) {
      for (final ex in workout.exercises) {
        if (ex.exerciseId != exerciseId) continue;
        for (final set in ex.sets) {
          if (!set.isCompleted || set.isWarmup) continue;
          final oneRM = set.estimatedOneRepMax;
          if (oneRM != null && oneRM > currentBest) {
            currentBest = oneRM;
            history.add(MapEntry(workout.startTime, oneRM));
          }
        }
      }
    }

    return history;
  }

  /// Workout frequency per month
  Map<String, int> getMonthlyWorkoutCount({int months = 6}) {
    final result = <String, int>{};
    final now = DateTime.now();

    for (int i = months - 1; i >= 0; i--) {
      final month = DateTime(now.year, now.month - i);
      final key = '${month.year}-${month.month.toString().padLeft(2, '0')}';
      result[key] = 0;
    }

    for (final workout in getCompletedWorkouts()) {
      final key =
          '${workout.startTime.year}-${workout.startTime.month.toString().padLeft(2, '0')}';
      if (result.containsKey(key)) result[key] = (result[key] ?? 0) + 1;
    }

    return result;
  }
}
